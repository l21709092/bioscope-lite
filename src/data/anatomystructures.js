export const PART_LIST = Object.entries(PARTS).map(([id, part]) => ({ id, ...part }));

export function partOpacity(meta, system, query) {
  const needle = query.trim().toLowerCase();
  const named = !needle || meta.name.toLowerCase().includes(needle);

  if (needle && named) {
    return system === "all" ? (meta.opacityAll ?? 1) : (meta.opacityFocus ?? 1);
  }

  if (needle && !named) {
    return meta.noGhost ? 0 : 0.03;
  }

  const inSystem = system === "all" || meta.systems.includes(system);
  if (!inSystem) return meta.noGhost ? 0 : 0.04;
  if (system === "all") return meta.opacityAll ?? 1;
  return meta.opacityFocus ?? 1;
}
